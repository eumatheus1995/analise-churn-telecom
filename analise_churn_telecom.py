import pandas as pd
import sqlite3

# Carregar o dataset
df = pd.read_csv('dataset_churn.csv')

# Converte automaticamente todas as colunas para minúsculas (opcional)
df.columns = df.columns.str.lower()

# Criar a conexão SQL na memória
conn = sqlite3.connect(':memory:')
df.to_sql('telecom_churn', conn, index=False, if_exists='replace')

print(f"Base real carregada com sucesso! Total de registros: {len(df)}")
df.head()

# Consulta SQL: Calcula o volume total de clientes e o percentual de cancelamento (Churn Rate) da base
print("=== 1. TAXA GERAL DE CHURN (SQL) ===")
query1 = """
SELECT
    churn,
    COUNT(*) as total_clientes,
    ROUND(COUNT(*) * 100.0 / (SELECT COUNT(*) FROM telecom_churn), 2) as porcentagem
FROM telecom_churn
GROUP BY churn;
"""
print(pd.read_sql_query(query1, conn))

# Consulta SQL: Cruza o tipo de contrato e a forma de pagamento para identificar onde ocorrem mais evasões
print("\n=== 2. CHURN POR FORMA DE PAGAMENTO (SQL) ===")
query2 = """
SELECT
    contract,
    payment_method,
    COUNT(*) as total_cancelamentos
FROM telecom_churn
WHERE churn = 'Yes'
GROUP BY contract, payment_method
ORDER BY total_cancelamentos DESC;
"""
print(pd.read_sql_query(query2, conn))

# Análise em Pandas: Compara a média de meses de permanência entre clientes ativos e os que cancelaram
print("\n=== 3. MÉDIA DE TEMPO DE CONTRATO (TENURE) EM PYTHON (PANDAS) ===")
media_tenure = df.groupby('churn')['tenure'].mean().round(1)
print(media_tenure)
